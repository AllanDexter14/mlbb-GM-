// Auto-fill potential where it isn't set by hand: current avg rating + an age-based growth bonus
function autoPotential() {
  for (const [name, f] of Object.entries(PLAYER_FORM)) {
    if (f.pot != null) continue;
    const age = PLAYER_META[name] && PLAYER_META[name].age;
    if (age == null) continue;
    const ovr = f.ovr != null ? f.ovr : Math.round((f.mec + f.mac + f.tf + f.con) / 4);
    const bonus = age <= 19 ? 9 : age <= 20 ? 8 : age <= 21 ? 6 : age <= 22 ? 5
                : age <= 23 ? 4 : age <= 24 ? 3 : age <= 25 ? 2 : age <= 27 ? 1 : 0;
    f.pot = Math.max(ovr, Math.min(97, ovr + bonus));
  }
}
